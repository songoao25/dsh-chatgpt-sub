// dsh-chatgpt-sub — build script
// 1) copy src/host.js -> lib/index.js（ESM host 插件）
// 2) wrap src/client-bundle.js -> lib/client.js（client-modules 经典脚本 bundle）
//    包装形态与官方 client 包一致：window.__ModuleLoader__.load({ id, factory })
// 用法：node scripts/build.mjs（package.json build/prepack 均调用）
import { copyFile, mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { LOCALES } from '../src/locales.js'
import { createLanguageRuntime } from '../src/language-runtime.js'

const root = dirname(fileURLToPath(new URL('../package.json', import.meta.url)))
const libDir = join(root, 'lib')

await rm(libDir, { recursive: true, force: true })
await mkdir(libDir, { recursive: true })

for (const file of ['self-update.js', 'version.js']) await copyFile(join(root, 'src', file), join(libDir, file))

// 1) host（ESM，原样复制，加文件头注释）
await writeFile(join(libDir, 'locales.js'), 'export const LOCALES = ' + JSON.stringify(LOCALES) + '\n')
const hostSource = await readFile(join(root, 'src', 'host.js'), 'utf8')
await writeFile(join(libDir, 'index.js'), `// Generated by scripts/build.mjs from src/host.js — do not edit directly.\n${hostSource}`)

// 2) client（CJS 模块源 → __ModuleLoader__ bundle）
// bundle id 必须等于包名（DSH 用它把 client bundle 和插件包对上），所以从 package.json
// 现读，而不是写死——以后再改名只动 package.json 一处。
const pkg = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'))
const clientSource = (await readFile(join(root, 'src', 'client-bundle.js'), 'utf8'))
  .replace('/*__LOCALES__*/{}', () => JSON.stringify(LOCALES))
  .replace('/*__LANGUAGE_RUNTIME__*/', () => createLanguageRuntime.toString())
const wrapped = [
  `window.__ModuleLoader__.load({ id: ${JSON.stringify(pkg.name)}, factory: (require) => {`,
  'var module = { exports: {} }; var exports = module.exports;',
  clientSource,
  'return module.exports;',
  '} });',
  '',
].join('\n')
await writeFile(join(libDir, 'client.js'), wrapped)

console.log('build OK → lib/index.js, lib/client.js')

await mkdir(join(root, 'locale'), { recursive: true })
// DSH 0.2.2 起，插件页的「详细介绍」优先读 locale meta.detail 指定的 Markdown，没声明才回退整篇 README。
// 只给确实准备了文档的语言声明；其余语言按 DSH 的语言链回退到 en（见 dsh-plugin-detail 的文档顺序）。
const DETAIL_DOCUMENTS = {
  en: 'docs/DETAIL.md',
  zh: 'docs/DETAIL.zh.md',
  'zh-hant': 'docs/DETAIL.zh-Hant.md',
}
for (const [language, dictionary] of Object.entries(LOCALES)) {
  const meta = { title: dictionary['meta.title'], description: dictionary['meta.description'] }
  const detail = DETAIL_DOCUMENTS[language]
  if (detail !== undefined) meta.detail = detail
  await writeFile(join(root, 'locale', language + '.json'), JSON.stringify({ meta }, null, 2) + '\n')
}
